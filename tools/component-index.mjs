// Writes COMPONENTS.md: every custom element Juel defines (its @customElement tag),
// the source file that defines it, and the example pages that use it.
// IMPROVEMENTS-PLAN 5.3. No dependencies: run `node tools/component-index.mjs`;
// `--check` exits 1 when COMPONENTS.md is out of date instead of writing it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, ext, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            if (entry.name !== 'node_modules') walk(full, ext, out);
        } else if (entry.name.endsWith(ext)) out.push(full);
    }
    return out;
}

const rel = file => path.relative(root, file).split(path.sep).join('/');

/** tag -> defining files, from `@customElement('tag')` in src/. */
export function findTags(srcFiles, read = f => fs.readFileSync(f, 'utf8')) {
    const tags = new Map();
    for (const file of srcFiles) {
        for (const m of read(file).matchAll(/@customElement\(\s*['"]([a-z][a-z0-9]*-[a-z0-9-]*)['"]\s*\)/g)) {
            if (!tags.has(m[1])) tags.set(m[1], []);
            tags.get(m[1]).push(file);
        }
    }
    return tags;
}

/** The page's Markdown, given the tags and, per tag, its source files and example pages (repo-relative). */
export function render(entries) {
    const lines = [
        '# Juel components',
        '',
        'Generated by `node tools/component-index.mjs` from the `@customElement` tags in `src/`',
        "and the `examples/` pages that use each one: don't edit by hand.",
        '',
        `${entries.length} custom elements.`,
        '',
        '| Element | Defined in | Examples |',
        '|---|---|---|',
    ];
    for (const { tag, sources, examples } of entries) {
        const ex = examples.length ? examples.map(e => `[${e.replace(/^examples\//, '')}](${e})`).join(', ') : '';
        lines.push(`| \`<${tag}>\` | ${sources.map(s => `\`${s}\``).join(', ')} | ${ex} |`);
    }
    return lines.join('\n') + '\n';
}

function build() {
    const tags = findTags(walk(path.join(root, 'src'), '.ts'));
    const pages = walk(path.join(root, 'examples'), '.html').map(f => ({ file: rel(f), text: fs.readFileSync(f, 'utf8') }));
    const entries = [...tags.keys()].sort().map(tag => {
        const open = new RegExp(`<${tag}[\\s>/]`);
        return {
            tag,
            sources: tags.get(tag).map(rel).sort(),
            examples: pages.filter(p => open.test(p.text)).map(p => p.file).sort(),
        };
    });
    return render(entries);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const out = path.join(root, 'COMPONENTS.md');
    const page = build();
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
        if (current !== page) {
            console.error('COMPONENTS.md is out of date: run `node tools/component-index.mjs`.');
            process.exit(1);
        }
        console.log('COMPONENTS.md is up to date.');
    } else {
        fs.writeFileSync(out, page);
        console.log('Wrote COMPONENTS.md.');
    }
}
